export type AoiConversationTone="early"|"close"|"romance"|"friendship";
export function aoiConversationTone(progress:CharacterProgress):AoiConversationTone {
  if(progress.route==="romance")return "romance";
  if(progress.route==="friendship")return "friendship";
  return progress.relationshipStage>=4?"close":"early";
}

