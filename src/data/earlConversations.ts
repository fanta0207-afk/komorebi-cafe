export type EarlConversationTone="early"|"close"|"romance"|"friendship";
export function earlConversationTone(progress:CharacterProgress):EarlConversationTone {
  if(progress.route==="romance")return "romance";
  if(progress.route==="friendship")return "friendship";
  return progress.relationshipStage>=4?"close":"early";
}
