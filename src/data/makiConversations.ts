export type MakiConversationTone="early"|"close"|"romance"|"friendship";
export function makiConversationTone(progress:CharacterProgress):MakiConversationTone {
  if(progress.route==="romance")return "romance";
  if(progress.route==="friendship")return "friendship";
  return progress.relationshipStage>=4?"close":"early";
}

