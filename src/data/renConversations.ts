export type RenConversationTone = "early"|"close"|"romance"|"friendship";
export function renConversationTone(progress:CharacterProgress):RenConversationTone {
  if(progress.route==="romance")return "romance";
  if(progress.route==="friendship")return "friendship";
  return progress.relationshipStage>=4?"close":"early";
}

