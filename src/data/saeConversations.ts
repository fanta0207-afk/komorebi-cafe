export type SaeConversationTone="early"|"close"|"romance"|"friendship";
export function saeConversationTone(progress:CharacterProgress):SaeConversationTone {
  if(progress.route==="romance")return "romance";
  if(progress.route==="friendship")return "friendship";
  return progress.relationshipStage>=4?"close":"early";
}
