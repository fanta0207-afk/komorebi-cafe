export type ShizukaConversationTone="early"|"close"|"romance"|"friendship";
export function shizukaConversationTone(progress:CharacterProgress):ShizukaConversationTone {
  if(progress.route==="romance")return "romance";
  if(progress.route==="friendship")return "friendship";
  return progress.relationshipStage>=4?"close":"early";
}
