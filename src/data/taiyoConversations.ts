export type TaiyoConversationTone="early"|"close"|"romance"|"friendship";
export function taiyoConversationTone(progress:CharacterProgress):TaiyoConversationTone {
  if(progress.route==="romance")return "romance";
  if(progress.route==="friendship")return "friendship";
  return progress.relationshipStage>=4?"close":"early";
}
